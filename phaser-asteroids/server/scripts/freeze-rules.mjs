// Freezes the CURRENT replay engine (simulation + verifier) as the server's verifier for the current gameplay rules version.
//
//   npm run rules:freeze              write server/rules/<version>/ (engine + reference replays) and its server/rules/versions.json entry
//   npm run rules:freeze -- --check   rebuild in a temporary folder and report whether the committed engine still matches; writes nothing
//   npm run rules:freeze -- --replace overwrite a version that is NOT yet on main (the CI guard refuses it for anything already released)
//
// It builds `src/replay/index.ts` exactly as `npm run build` does for dist/node (one self-contained ES module, no imports), copies it to
// server/rules/<version>/engine.mjs, then uses THAT file and the test bot to record reference replays with the results that engine
// computes for them. server/tests/rulesCompat.test.ts replays them through the frozen engine and, for the current version, through the
// live sources too: a gameplay change made without a rules version bump fails there. See server/rules/README.md.

import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import zlib from 'node:zlib';
import { digest } from '../rules/policy.mjs';
import { generateBotReplay } from '../testing/bot.mjs';

const serverDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const root = path.resolve(serverDir, '..');
const rulesDir = path.join(serverDir, 'rules');
const manifestPath = path.join(rulesDir, 'versions.json');

const RANKED_TICKS = 72_000; // 20 minutes at 60 Hz: what the server issues (config.ts MAX_RANKED_TICKS)
const ranked = { maxTicks: RANKED_TICKS, requireGameOver: true, timeLimitTicks: RANKED_TICKS };
const SHORT_LIMIT = 1800;

/** The reference replays recorded for every frozen version. Each one pins a different part of the verifier's behaviour. */
const FIXTURES = [
  { name: 'game-over-reference', note: 'the bot plays seed 54321 until game over (the server tests use the same game)', bot: { seed: 54321 }, options: ranked },
  { name: 'game-over-stress', note: 'an aggressive bot on another seed, until game over', bot: { seed: 20261102, stress: true }, options: ranked },
  { name: 'time-limit', note: `still alive at an issued ${SHORT_LIMIT}-tick limit: a valid time_limit ending`, bot: { seed: 54321, maxTicks: SHORT_LIMIT }, options: { maxTicks: SHORT_LIMIT, requireGameOver: true, timeLimitTicks: SHORT_LIMIT } },
  { name: 'stopped-early', note: 'stops while alive, before the limit: must be rejected', bot: { seed: 54321, maxTicks: 900 }, options: ranked },
  { name: 'forged-claim', note: 'the reference game with its claimed score raised by 1000: must be rejected', bot: { seed: 54321 }, options: ranked, forge: (r) => void (r.claimedResult.score += 1000) },
];

const git = (...args) => spawnSync('git', args, { cwd: root, encoding: 'utf8' }).stdout.trim();

function buildEngine(outDir) {
  const vite = path.join(root, 'node_modules', 'vite', 'bin', 'vite.js');
  const res = spawnSync(process.execPath, [vite, 'build', '--outDir', outDir, '--emptyOutDir', '--target', 'node20', '--ssr', 'src/replay/index.ts', '--logLevel', 'warn'], { cwd: root, stdio: 'inherit' });
  if (res.status !== 0) throw new Error(`vite build failed (exit ${res.status ?? res.signal})`);
  return fs.readFileSync(path.join(outDir, 'index.js'));
}

function header(version, schema) {
  const commit = git('rev-parse', '--short', 'HEAD') || 'unknown';
  const dirty = git('status', '--porcelain', '--', 'src/core', 'src/replay') ? ' plus uncommitted changes to src/core or src/replay' : '';
  return (
    `// FROZEN replay engine for gameplay rules ${version} (replay schema ${schema}). Generated by \`npm run rules:freeze\` from ${commit}${dirty}.\n` +
    `// Never edit this file: the server verifies every ${version} run with it, and its hash is pinned in ../versions.json. See ../README.md.\n`
  );
}

/** Types for engine.mjs: only what server/src/engines.ts relies on (it checks them at load time too). Same for every version. */
const TYPES = `// Types for engine.mjs, generated by \`npm run rules:freeze\`. Only what server/src/engines.ts uses. Never edit: see ../README.md.
export declare const GAMEPLAY_RULES_VERSION: string;
export declare const REPLAY_SCHEMA_VERSION: number;
export declare const FIXED_TICK_RATE: number;
export declare function verifyReplay(replay: unknown, options?: object): unknown;
`;

export function fixtureResults(engine) {
  return FIXTURES.map((f) => {
    const run = generateBotReplay(engine, f.bot);
    const replay = structuredClone(run.replay);
    f.forge?.(replay);
    const expected = engine.verifyReplay(replay, f.options);
    return { name: f.name, fixture: { note: f.note, options: f.options, expected, replay } };
  });
}

async function main() {
  const check = process.argv.includes('--check');
  const replace = process.argv.includes('--replace');
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'rules-freeze-'));
  try {
    const built = buildEngine(tmp);
    const probe = await import(pathToFileURL(path.join(tmp, 'index.js')).href);
    const version = probe.GAMEPLAY_RULES_VERSION;
    const schema = probe.REPLAY_SCHEMA_VERSION;
    const dir = path.join(rulesDir, version);
    const enginePath = path.join(dir, 'engine.mjs');
    const existing = fs.existsSync(enginePath) ? fs.readFileSync(enginePath) : null;
    const body = (buf) => buf.toString('utf8').split('\n').filter((l) => !l.startsWith('// FROZEN') && !l.startsWith('// Never edit')).join('\n');
    const same = existing !== null && body(existing) === body(built);

    if (check) {
      console.log(existing === null ? `rules ${version} is not frozen yet` : same ? `rules ${version}: the frozen engine matches the current sources byte for byte` : `rules ${version}: the current sources build a DIFFERENT engine than the frozen one (fine if only non-gameplay code changed; the reference replays decide)`);
      return;
    }
    if (existing !== null && !same && !replace) {
      throw new Error(`server/rules/${version}/ already exists and the current sources build a different engine. If gameplay changed, bump GAMEPLAY_RULES_VERSION in src/replay/constants.ts and freeze again. Use --replace only for a version that has never been merged to main.`);
    }
    if (existing !== null && same && !replace) {
      console.log(`rules ${version} is already frozen and unchanged; nothing to do`);
      return;
    }

    fs.rmSync(dir, { recursive: true, force: true });
    fs.mkdirSync(path.join(dir, 'fixtures'), { recursive: true });
    fs.writeFileSync(enginePath, header(version, schema) + built.toString('utf8'));
    const engine = await import(`${pathToFileURL(enginePath).href}?t=${Date.now()}`);
    if (engine.GAMEPLAY_RULES_VERSION !== version || typeof engine.verifyReplay !== 'function') throw new Error('frozen engine does not load');

    fs.writeFileSync(path.join(dir, 'engine.d.mts'), TYPES);

    const files = { 'engine.mjs': digest(fs.readFileSync(enginePath), 'engine.mjs'), 'engine.d.mts': digest(TYPES, 'engine.d.mts') };
    for (const { name, fixture } of fixtureResults(engine)) {
      // gzip: the bot changes its input almost every tick, so a 20 000-tick game is ~1.7 MB of JSON and ~110 KB compressed.
      const rel = `fixtures/${name}.json.gz`;
      const bytes = zlib.gzipSync(JSON.stringify(fixture), { level: 9 });
      fs.writeFileSync(path.join(dir, rel), bytes);
      files[rel] = digest(bytes, rel);
      const e = fixture.expected;
      console.log(`  ${rel.padEnd(37)} valid=${e.valid} score=${e.calculatedScore} ticks=${e.totalTicks} end=${e.endReason ?? '-'} (${Math.round(bytes.length / 1024)} KB)`);
    }

    const manifest = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, 'utf8')) : { versions: {} };
    manifest.versions[version] = { schemaVersion: schema, frozenAt: new Date().toISOString().slice(0, 10), files };
    manifest.versions = Object.fromEntries(Object.entries(manifest.versions).sort(([a], [b]) => a.localeCompare(b, 'en', { numeric: true })));
    fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

    console.log(`\nFroze rules ${version} (schema ${schema}) into server/rules/${version}/ and server/rules/versions.json.`);
    console.log(`Next: register it in server/src/engines.ts:\n  import * as rules_${version.replace(/\W/g, '_')} from '../rules/${version}/engine.mjs';\n  ...registry([..., frozen(rules_${version.replace(/\W/g, '_')})])`);
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => {
    console.error(`[rules:freeze] ${e instanceof Error ? e.message : e}`);
    process.exit(1);
  });
}
