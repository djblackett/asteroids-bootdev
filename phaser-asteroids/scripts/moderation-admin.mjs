// Real browser + disposable local Worker/D1. Never connects to production.
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright-core';
import { WorkerStack, findChrome, makeChecker, root } from './lib/rankedStack.mjs';

const token = 'local-admin-browser-test-0123456789';
const stack = new WorkerStack({port: Number(process.env.MODERATION_TEST_PORT ?? 8797), vars: {ADMIN_TOKEN:token}});
const {check,state} = makeChecker();
let browser;
const id = crypto.randomUUID(), other = crypto.randomUUID();
try {
  const migration = stack.migrate();
  if (!check('migrations apply in local D1',migration.ok,migration.output)) throw new Error('Migration failed');
  const now = Date.now();
  const seed = (scoreId,name) => `INSERT INTO runs (id,token_hash,seed,rules_version,config_json,created_at,expires_at,status,score_id) VALUES ('run-${scoreId}','test',1,'1.2.0','{}',${now},${now + 3600000},'accepted','${scoreId}');
    INSERT INTO scores (id,run_id,score,nickname,completed_at,rules_version,ticks,duration_ms,asteroids_destroyed) VALUES ('${scoreId}','run-${scoreId}',100,'${name}',${now},'1.2.0',3600,60000,1);`;
  if (!stack.exec(seed(id,'<img src=x>') + seed(other,'Other Pilot'))) throw new Error('Seed failed');
  await stack.start();
  const report = reason => fetch(stack.API + '/api/v1/scores/' + id + '/report', {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({reason})});
  check('report enters real D1 through public API',(await report('offensive')).status === 200);
  browser = await chromium.launch({executablePath:findChrome(),headless:true});
  const page = await browser.newPage({viewport:{width:1200,height:900}});
  const errors = [];
  page.on('pageerror',e => errors.push(String(e)));
  page.on('dialog',async dialog => dialog.accept(dialog.type() === 'prompt' ? id : undefined));
  const publicScore = async () => { const r = await fetch(stack.API + '/api/v1/scores/' + id); return {status:r.status,headers:r.headers,body:await r.json()}; };
  await page.goto(stack.API + '/admin');
  check('no private entries before authentication',await page.locator('article').count() === 0);
  await page.locator('#token').fill('incorrect');
  await page.getByRole('button',{name:'Unlock',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('credentials'));
  check('invalid login stays locked',await page.locator('#console').isHidden());
  await page.locator('#token').fill(token);
  await page.getByRole('button',{name:'Unlock',exact:true}).click();
  await page.locator('article').waitFor();
  check('report queue shows only reported entry',await page.locator('article').count() === 1);
  check('input clears and browser storage contains no token',await page.locator('#token').inputValue() === '' && await page.evaluate(() => localStorage.length === 0 && sessionStorage.length === 0));
  check('stored text is rendered literally without markup',await page.locator('article h2').textContent().then(t => t.includes('<img')) && await page.locator('article img').count() === 0);
  await page.getByRole('button',{name:'Reports / decision history',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('article pre').textContent.includes('offensive'));
  check('administrator sees report categories',await page.locator('article pre').textContent().then(t => t.includes('1 open / offensive')));
  await report('personal_info');
  await page.getByRole('button',{name:'Hide',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('This entry changed'));
  check('new report invalidates stale operator decision in D1',(await publicScore()).status === 200);
  await page.getByRole('button',{name:'Refresh',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('article small').textContent.includes('revision 2'));
  async function action(label) {
    const done = page.waitForResponse(r => r.url().endsWith('/moderate') && r.request().method() === 'POST');
    await page.getByRole('button',{name:label,exact:true}).click();
    const res = await done;
    await page.waitForFunction(() => document.querySelector('#status').textContent === 'Decision saved with audit record.');
    // Wait for the refresh response's DOM, then clear status for the next action.
    await page.evaluate(() => document.querySelector('#status').textContent = '');
    check(label + ' commits through real Worker',res.status() === 200);
  }
  await action('Replace name');
  check('public replacement preserves verified score',(await publicScore()).body.score.nickname === 'Anonymous' && (await publicScore()).body.score.score === 100);
  await action('Hide');
  check('hidden detail is immediately unavailable',(await publicScore()).status === 404);
  const board = await fetch(stack.API + '/api/v1/leaderboard/all-time');
  check('public board is not cached and excludes hidden entry',board.headers.get('Cache-Control') === 'no-store' && (await board.json()).entries.every(e => e.id !== id));
  await action('Restore score');
  await action('Restore original name');
  check('original name can be restored',(await publicScore()).body.score.nickname === '<img src=x>');
  await action('Resolve reports / flag');
  check('resolution clears queue',await page.locator('article').count() === 0);
  await page.locator('#lookup').fill(id);
  await page.locator('#filter').selectOption('all');
  await page.locator('article').waitFor();
  await action('Reopen review');
  await page.getByRole('button',{name:'Reports / decision history',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('article pre').textContent.includes('reopen'));
  check('decision history remains available',await page.locator('article pre').textContent().then(t => t.includes('rename') && t.includes('restore_name')));
  const out = path.join(root,'scripts','.smoke-output'); fs.mkdirSync(out,{recursive:true});
  await page.screenshot({path:path.join(out,'moderation-admin-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  check('console fits a phone width',await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({path:path.join(out,'moderation-admin-phone.png'),fullPage:true});
  await page.getByRole('button',{name:'Erase score and linked records',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.startsWith('Entry and linked run/reports erased'));
  check('erasure removes public score',(await publicScore()).status === 404);
  check('erasure preserves unrelated entry',(await fetch(stack.API + '/api/v1/scores/' + other)).status === 200);
  check('local D1 has only unrelated score/run and no reports',stack.sql('SELECT (SELECT COUNT(*) FROM scores) AS scores, (SELECT COUNT(*) FROM runs) AS runs, (SELECT COUNT(*) FROM score_reports) AS reports')?.every(r => r.scores === 1 && r.runs === 1 && r.reports === 0));
  await page.getByText('Audit log (all decisions, including anonymous erasures)',{exact:true}).click();
  await page.getByRole('button',{name:'Latest 100',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#audit-log').textContent.includes('delete'));
  check('anonymous erasure audit visible',await page.locator('#audit-log').textContent().then(t => t.includes('[erased entry]')));
  await page.reload();
  check('reload locks the console',await page.locator('#console').isHidden() && await page.locator('article').count() === 0);
  check('console JavaScript has no runtime errors',errors.length === 0,errors.join(';'));
} finally { await browser?.close(); stack.cleanup(); }
console.log(`${state.total-state.failures}/${state.total} moderation browser checks passed`);
process.exitCode = state.failures ? 1 : 0;
